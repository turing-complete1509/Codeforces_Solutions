#include <bits/stdc++.h>
using namespace std;

#define ll long long
#define nl '\n'
#define all(v) v.begin(), v.end()

template <typename T>
void debug(const vector<T>& arr) {
    for(const auto& x: arr) cout << x << " ";
    cout << nl;
}

long long gcd(long long a, long long b) { return b==0?a:gcd(b,a%b); }
long long lcm(long long a, long long b) { return (a/gcd(a,b))*b; }


void solve() {
    int l, r;
    cin>>l>>r;
    if(r-l+1==1){
        cout<<0<<endl;
        return;
    }
    if((r>0 && l>0) || (l<0 && r<0)){
        cout<<(r-l)<<endl;
    }else if(l==0 || r==0){
        cout<<(r-l-1)<<endl;
    }else{
        if(abs(r)==abs(l)){
            cout<<0<<endl;
        }else if(abs(l) > abs(r)){
            cout<<(abs(l) - abs(r)-1)<<endl;
        }else{
            cout<<(abs(r) - abs(l)-1)<<endl;
        }
    }
}

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    
    int t=1;
    cin >> t;
    while(t--) {
        solve();
    }
    
    return 0;
}