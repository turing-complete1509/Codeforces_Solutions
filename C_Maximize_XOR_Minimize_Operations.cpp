#include <bits/stdc++.h>
using namespace std;

#define ll long long
#define nl '\n'
#define all(v) v.begin(), v.end()

template <typename T>
void debug(const vector<T>& arr) {
    for(const auto& x: arr) cout << x << " ";
    cout << nl;
}

long long gcd(long long a, long long b) { return b==0?a:gcd(b,a%b); }
long long lcm(long long a, long long b) { return (a/gcd(a,b))*b; }

void solve() {
    ll x, y;
    cin>>x>>y;
    ll res = x+y;
    ll final_x = 0;
    for(int i=31; i>=0; i--){
        if((res & (1LL<<i)) != 0){
            ll new_x = final_x | (1<<i);
            if(new_x<=x){
                final_x = new_x;
            }
        }
    }
    ll val = final_x ^ (res-final_x);
    cout<<val<<" "<<x-final_x<<endl;
}

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    
    int t=1;
    cin >> t;
    while(t--) {
        solve();
    }
    
    return 0;
}