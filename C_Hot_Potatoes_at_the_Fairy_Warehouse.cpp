long long gcd(long long a, long long b) { return b==0?a:gcd(b,a%b); }
long long lcm(long long a, long long b) { return (a/gcd(a,b))*b; }

void solve() {
    int n, k;
    cin>>n>>k;
    string s;
    cin>>s;
    n*=2;
    string res = s;
    for(int i=0; i<n; i++){
        if(s[i]=='1' && s[(i+1)%n]=='0'){
            res[i] = '0';
            res[(i+1)%n] = '1';
        }
    }
    // cout<<res<<endl;
    int evenCount = 0;
    int oddCount = 0;
    for(int i=0; i<n; i++){
        if(res[i]=='0'){
            continue;
        }
        if(i%2==0){
            oddCount++;
        }else{
            evenCount++;
        }
    }
    cout<<evenCount<<" "<<oddCount<<endl;
}

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    
    int t=1;
    cin >> t;
    while(t--) {
        solve();
    }
    
    return 0;
}